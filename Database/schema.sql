CREATE TABLE IF NOT EXISTS customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(160) NOT NULL,
    email varchar(254),
    phone varchar(32),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(64) NOT NULL UNIQUE,
    name varchar(180) NOT NULL,
    description text,
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    stock_quantity integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference varchar(32) NOT NULL UNIQUE,
    customer_id bigint REFERENCES customers(id) ON DELETE SET NULL,
    sold_at timestamptz NOT NULL DEFAULT now(),
    total_amount numeric(12, 2) NOT NULL CHECK (total_amount >= 0),
    status varchar(24) NOT NULL DEFAULT 'Completada'
        CHECK (status IN ('Completada', 'Anulada'))
);

CREATE TABLE IF NOT EXISTS sale_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id bigint NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
    product_id bigint REFERENCES products(id) ON DELETE SET NULL,
    product_name varchar(180) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
    line_total numeric(12, 2) NOT NULL CHECK (line_total >= 0)
);

CREATE INDEX IF NOT EXISTS ix_sales_sold_at ON sales (sold_at DESC);
CREATE INDEX IF NOT EXISTS ix_sales_customer_id ON sales (customer_id);
CREATE INDEX IF NOT EXISTS ix_customers_active_created
    ON customers (is_active, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_sale_items_sale_id ON sale_items (sale_id);
